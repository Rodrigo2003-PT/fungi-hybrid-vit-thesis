def map_descriptors(cam: np.ndarray) -> Dict[str, float]:
    flat = cam.ravel().astype(np.float64)
    n = flat.size
    s = flat.sum()
    sv = np.sort(flat)
    sci = 0.0 if s < 1e-12 else float((2.0 * (np.arange(1, n + 1) * sv).sum()) / (n * s) - (n + 1) / n)
    ent = 0.0 if s < 1e-12 else float(-np.sum((flat / s) * np.log(flat / s + 1e-10)))
    return {"sci": float(np.clip(sci, 0.0, 1.0)), "entropy": ent,
            "active_fraction": float((flat > 0.5).mean()), "peak_response": float(flat.max()),
            "border_mass": float(cam[BAND].sum() / s) if s > 1e-12 else float("nan")}


