def _rank_pixels(cam: np.ndarray) -> np.ndarray:
    return np.argsort(cam.flatten())[::-1].copy()


def _pixel_checkpoints(n_pixels: int, n_steps: int) -> np.ndarray:
    return np.linspace(0, n_pixels, n_steps + 1, dtype=int)


def _forward_probs(batch: torch.Tensor, cls: int) -> np.ndarray:
    with torch.no_grad():
        with torch.autocast(device_type=DEVICE.type, dtype=torch.float16, enabled=AMP):
            lg = model(batch.to(DEVICE))
        return F.softmax(lg.float(), dim=1)[:, cls].cpu().numpy().astype(np.float32)


def _pixel_curve(x: torch.Tensor, order: np.ndarray, cls: int, n_steps: int, mode: str) -> np.ndarray:
    _, H, W = x.shape
    cps = _pixel_checkpoints(H * W, n_steps)
    if mode == "deletion":
        batch = x.unsqueeze(0).expand(n_steps + 1, -1, -1, -1).clone()
    else:
        batch = torch.full((n_steps + 1, x.shape[0], H, W), CONFIG["canvas_value"], dtype=x.dtype)
    prev = 0
    for k, n in enumerate(cps):
        n = int(n)
        if n > prev:
            idx = order[prev:n]
            r, c = idx // W, idx % W
            batch[k:, :, r, c] = CONFIG["canvas_value"] if mode == "deletion" else x[:, r, c]
        prev = n
    return _forward_probs(batch, cls)


