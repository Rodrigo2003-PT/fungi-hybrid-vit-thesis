class GradCAM:
    """Grad-CAM at a target layer; returns upsampled maps plus native and pre-ReLU maps."""

    def __init__(self, model: nn.Module, target_layer: nn.Module):
        self.model, self.acts, self.grads = model, None, None
        self.h1 = target_layer.register_forward_hook(lambda m, i, o: setattr(self, "acts", o.detach()))
        self.h2 = target_layer.register_full_backward_hook(lambda m, gi, go: setattr(self, "grads", go[0].detach()))

    def remove(self) -> None:
        self.h1.remove()
        self.h2.remove()

    def __call__(self, x: torch.Tensor):
        B, _, H, W = x.shape
        amp = CONFIG["use_amp"] and x.device.type == "cuda"
        self.model.eval()
        with torch.autocast(device_type=x.device.type, dtype=torch.float16, enabled=amp):
            logits = self.model(x)
        logits32 = logits.float()
        pred = logits32.argmax(1).cpu().numpy()
        acts = self.acts.float()
        cams, natives, prerelus = [], [], []
        for b in range(B):
            self.model.zero_grad()
            logits32[b, int(pred[b])].backward(retain_graph=(b < B - 1))
            alpha = self.grads[b].float().mean(dim=(1, 2))
            weighted = (alpha[:, None, None] * acts[b]).sum(0)
            cam = F.relu(weighted)
            prerelus.append(weighted.detach().cpu().numpy().astype(np.float32))
            natives.append(cam.detach().cpu().numpy().astype(np.float32))
            up = F.interpolate(cam[None, None], size=(H, W), mode="bilinear", align_corners=False).squeeze()
            up = up.cpu().numpy()
            lo, hi = up.min(), up.max()
            up = (up - lo) / (hi - lo) if hi - lo > 1e-8 else np.zeros_like(up)
            cams.append(up.astype(np.float32))
        return (np.stack(cams), np.stack(natives), np.stack(prerelus), pred,
                logits32.detach().cpu().numpy())


