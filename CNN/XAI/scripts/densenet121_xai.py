class DenseNet121Classifier(nn.Module):
    """Single-channel DenseNet-121 with a linear head (architecture of the trained checkpoint)."""

    def __init__(self, num_classes: int = 2, channels: int = 1):
        super().__init__()
        backbone = torchvision.models.densenet121(weights=None)
        c0 = backbone.features.conv0
        backbone.features.conv0 = nn.Conv2d(channels, c0.out_channels, kernel_size=c0.kernel_size,
                                            stride=c0.stride, padding=c0.padding, bias=False)
        backbone.classifier = nn.Linear(backbone.classifier.in_features, num_classes)
        self.features = backbone.features
        self.classifier = backbone.classifier

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        out = F.relu(self.features(x), inplace=True)
        out = F.adaptive_avg_pool2d(out, (1, 1))
        return self.classifier(torch.flatten(out, 1))


def load_final_model(path: str, device: torch.device) -> Tuple[nn.Module, Dict[str, Any]]:
    ckpt = torch.load(path, map_location=device, weights_only=False)
    mc = dict(ckpt["config"]["model_config"])
    num_classes = int(mc.pop("num_classes"))
    channels = int(mc.pop("channels", 1))
    model = DenseNet121Classifier(num_classes=num_classes, channels=channels).to(device)
    model.load_state_dict(ckpt["model_state_dict"], strict=True)
    model.eval()
    for p in model.parameters():
        p.requires_grad_(True)          # Grad-CAM needs gradients w.r.t. activations
    meta = {"mean": np.atleast_1d(np.asarray(ckpt["mean"], dtype=np.float32)),
            "std": np.atleast_1d(np.asarray(ckpt["std"], dtype=np.float32)),
            "class_to_idx": dict(ckpt["class_to_idx"]),
            "metadata": ckpt.get("metadata", {})}
    return model, meta


