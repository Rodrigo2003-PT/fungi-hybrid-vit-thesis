def params_hash(d: Dict[str, Any]) -> str:
    return hashlib.sha256(json.dumps(d, sort_keys=True).encode()).hexdigest()[:10]


def cached_run(name: str, params: Dict[str, Any], fn, indices: np.ndarray) -> List[Dict[str, Any]]:
    """Run fn(i) for each index with a per-image .npz cache on Drive."""
    d = os.path.join(CACHE_DIR, f"{name}_{CKPT_SHA[:12]}_{params_hash(params)}")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "params.json"), "w") as f:
        json.dump(params, f, indent=1)
    out, t0, n_new = [], time.time(), 0
    for j, i in enumerate(indices):
        p = os.path.join(d, f"{int(i):04d}.npz")
        if os.path.exists(p):
            z = np.load(p)
            out.append({k: (z[k] if z[k].ndim else z[k].item()) for k in z.files})
        else:
            r = fn(int(i))
            np.savez_compressed(p, **{k: np.asarray(v) for k, v in r.items()})
            out.append(r)
            n_new += 1
        if (j + 1) % 25 == 0 or j + 1 == len(indices):
            el = time.time() - t0
            rate = el / max(n_new, 1)
            left = sum(1 for ii in indices[j + 1:] if not os.path.exists(os.path.join(d, f"{int(ii):04d}.npz")))
            print(f"  {name}: {j + 1}/{len(indices)} images ({n_new} computed, {rate:.1f} s/img, "
                  f"about {left * rate / 60:.0f} min left)", flush=True)
    return out

