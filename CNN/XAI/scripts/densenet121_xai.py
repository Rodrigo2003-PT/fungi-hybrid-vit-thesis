def to_uint8(img: np.ndarray) -> np.ndarray:
    img = img.astype(np.float32)
    lo, hi = img.min(), img.max()
    img = (img - lo) / (hi - lo) if hi - lo > 1e-8 else np.zeros_like(img)
    return (img * 255).clip(0, 255).astype(np.uint8)


def overlay(cam: np.ndarray, img_u8: np.ndarray, alpha: float = 0.5) -> np.ndarray:
    heat = (plt.colormaps[HEATMAP_CMAP](cam)[..., :3] * 255).astype(np.float32)
    rgb = np.repeat(img_u8[..., None], 3, axis=2).astype(np.float32)
    return ((1 - alpha) * rgb + alpha * heat).clip(0, 255).astype(np.uint8)


