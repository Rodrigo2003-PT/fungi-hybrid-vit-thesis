GRID, CELL_PX, N_CELLS = 12, 32, 144
DIAG_CELLS = (14, 36, 72)          # about 10 %, 25 %, 50 % of the cells


def cell_steps(n_steps: int = N_CELLS) -> np.ndarray:
    n_k = np.rint(np.arange(n_steps + 1) * N_CELLS / n_steps).astype(np.int64)
    n_k[0], n_k[-1] = 0, N_CELLS
    return n_k


def has_ties(native: np.ndarray, tie_break: str, prerelu: Optional[np.ndarray]) -> bool:
    v = np.asarray(native, np.float64).ravel()
    if tie_break == "prerelu":
        keys = np.stack([v, np.asarray(prerelu, np.float64).ravel()], 1)
        return np.unique(keys, axis=0).shape[0] < v.size
    return np.unique(v).size < v.size


def rank_cells(native: np.ndarray, rng: np.random.Generator, tie_break: str = "random",
               prerelu: Optional[np.ndarray] = None) -> np.ndarray:
    v = np.asarray(native, np.float64).ravel()
    if v.size != N_CELLS or np.any(v < 0):
        raise ValueError("native map must be a rectified 12 x 12 map")
    keys = [rng.random(N_CELLS)]
    if tie_break == "prerelu":
        keys.append(-np.asarray(prerelu, np.float64).ravel())
    elif tie_break != "random":
        raise ValueError(tie_break)
    keys.append(-v)
    return np.lexsort(tuple(keys)).astype(np.int64)


def cell_masks(order: np.ndarray, n_k: np.ndarray, mode: str) -> np.ndarray:
    rank = np.empty(N_CELLS, np.int64)
    rank[order] = np.arange(N_CELLS)
    if mode == "deletion":
        return rank[None, :] < n_k[:, None]
    if mode == "insertion":
        return rank[None, :] >= n_k[:, None]
    raise ValueError(mode)


def mask_geometry(masked: np.ndarray) -> Tuple[int, int]:
    m = np.asarray(masked, bool).reshape(GRID, GRID)
    _, n_comp = nd_label(m)
    edges = int((m[:, 1:] != m[:, :-1]).sum() + (m[1:, :] != m[:-1, :]).sum())
    return int(n_comp), edges


def trapezoid_auc(curve: np.ndarray) -> float:
    c = np.asarray(curve, np.float64)
    return float((c[:-1] + c[1:]).sum() / (2.0 * (c.size - 1)))


def softmax_np(z: np.ndarray) -> np.ndarray:
    z = z - z.max(1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(1, keepdims=True)


def image_cell_curves(evaluate, native, pred_class, rng_rank, rng_rand, n_steps=144, n_random=10,
                      n_tie_draws=10, tie_break="random", prerelu=None, compute_random=True):
    n_k = cell_steps(n_steps)
    S = n_steps + 1
    n_rank = n_tie_draws if has_ties(native, tie_break, prerelu) else 1
    orders = {"gradcam": [rank_cells(native, rng_rank, tie_break, prerelu) for _ in range(n_rank)]}
    if compute_random:
        orders["random"] = [rng_rand.permutation(N_CELLS).astype(np.int64) for _ in range(n_random)]
    blocks, layout = [], []
    for variant, ords in orders.items():
        for mode in ("deletion", "insertion"):
            for o in ords:
                blocks.append(cell_masks(o, n_k, mode))
                layout.append((variant, mode))
    allm = np.concatenate(blocks)
    uniq, inv = np.unique(np.packbits(allm, axis=1), axis=0, return_inverse=True)
    uniq_masks = np.unpackbits(uniq, axis=1, count=N_CELLS).astype(bool)
    logits = np.asarray(evaluate(uniq_masks), np.float64)[np.asarray(inv).ravel()]
    prob = softmax_np(logits)[:, pred_class]
    margin = logits[:, pred_class] - np.delete(logits, pred_class, axis=1).max(1)
    out = {"n_unique_frames": int(uniq_masks.shape[0]), "n_rank_draws": n_rank,
           "n_zero_cells": int((np.asarray(native) == 0).sum())}
    for variant in orders:
        for mode in ("deletion", "insertion"):
            rows = [j for j, lm in enumerate(layout) if lm == (variant, mode)]
            pc = np.stack([prob[j * S:(j + 1) * S] for j in rows]).mean(0)
            mc = np.stack([margin[j * S:(j + 1) * S] for j in rows]).mean(0)
            out[f"{variant}_{mode}_prob"] = pc.astype(np.float32)
            out[f"{variant}_{mode}_margin"] = mc.astype(np.float32)
            out[f"auc_{variant}_{mode}"] = trapezoid_auc(pc)
        for n in DIAG_CELLS:
            g = np.array([mask_geometry(cell_masks(o, np.array([n]), "deletion")[0]) for o in orders[variant]])
            out[f"diag_{variant}_comp_{n}"] = float(g[:, 0].mean())
            out[f"diag_{variant}_edges_{n}"] = float(g[:, 1].mean())
    return out


