def f3(v):
    return "nan" if v != v else f"{v:.3f}"


def sg3(v):
    return "nan" if v != v else (f"{v:+.3f}".replace("-", "$-$") if v < 0 else f"{v:+.3f}")


def pv(p):
    if p != p:
        return "n/a"
    if abs(p - 1 / 4096) < 1e-12:
        return "1/4096"
    return f"{p:.4f}" if p < 0.01 else f"{p:.3f}"


