def make_cell_evaluator(x: torch.Tensor, amp: bool = AMP, batch: int = CONFIG["eval_batch"]):
    x = x.to(DEVICE)
    canvas_t = torch.tensor(CONFIG["canvas_value"], dtype=x.dtype, device=DEVICE)

    def evaluate(masks: np.ndarray) -> np.ndarray:
        m_all = torch.from_numpy(np.ascontiguousarray(masks).reshape(-1, 1, GRID, GRID))
        out = []
        with torch.no_grad():
            for s in range(0, m_all.shape[0], batch):
                m = m_all[s:s + batch].to(DEVICE).repeat_interleave(CELL_PX, 2).repeat_interleave(CELL_PX, 3)
                xb = torch.where(m, canvas_t, x.unsqueeze(0))
                with torch.autocast(device_type=DEVICE.type, dtype=torch.float16, enabled=amp):
                    lg = model(xb)
                out.append(lg.float().cpu().numpy())
        return np.concatenate(out).astype(np.float64)

    return evaluate


