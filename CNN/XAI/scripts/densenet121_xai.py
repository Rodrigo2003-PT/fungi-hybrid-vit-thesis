def decomposition(cell, pixel):
    rows = []
    slides = cell["slide_groups"]
    yt, yp = cell["true_labels"], cell["predicted_classes"]
    for proto, g, r in (("deletion", "audc_gradcam", "audc_random"), ("insertion", "auic_gradcam", "auic_random")):
        sgn = 1.0 if proto == "deletion" else -1.0
        groups = [(SHORT[CLASS_NAMES[c]], (yt == c) & (yt == yp), False) for c in range(len(CLASS_NAMES))]
        groups.append(("slide", np.ones(len(yt), bool), True))
        for name, m, slide_level in groups:
            def agg(a):
                a = np.asarray(a, np.float64)
                if not m.any():
                    return float("nan")
                if slide_level:
                    return float(np.mean([a[m & (slides == s)].mean() for s in np.unique(slides[m])]))
                return float(a[m].mean())
            Gp, Rp, Gc, Rc = agg(pixel[g]), agg(pixel[r]), agg(cell[g]), agg(cell[r])
            rows.append({"protocol": proto, "group": name, "G_px": Gp, "R_px": Rp, "gap_px": sgn * (Rp - Gp),
                         "G_cell": Gc, "R_cell": Rc, "gap_cell": sgn * (Rc - Gc),
                         "random_geometry": sgn * (Rp - Rc), "ranked_unit": sgn * (Gc - Gp)})
    df = pd.DataFrame(rows)
    df["gap_difference"] = df["gap_px"] - df["gap_cell"]
    assert np.nanmax(np.abs(df["gap_difference"] - df["random_geometry"] - df["ranked_unit"])) < 1e-9
    return df


