def _inferential_stats(a, b, alternative="greater", n_bootstrap=2000, ci=0.95, rng_seed=0, slide_groups=None):
    d = a - b
    n = len(d)
    rng = np.random.default_rng(rng_seed)
    if slide_groups is not None:
        unique_slides = np.unique(slide_groups)
        n_slides = len(unique_slides)
        slide_deltas = np.array([d[slide_groups == s].mean() for s in unique_slides], dtype=np.float64)
        if n_slides >= 10:
            nonzero_s = slide_deltas[slide_deltas != 0]
            if len(nonzero_s) >= 10:
                w_stat, w_pval = wilcoxon(nonzero_s, alternative=alternative)
            else:
                w_stat, w_pval = float("nan"), float("nan")
        else:
            w_stat, w_pval = float("nan"), float("nan")
        boot = np.empty(n_bootstrap)
        for k in range(n_bootstrap):
            boot[k] = slide_deltas[rng.integers(0, n_slides, size=n_slides)].mean()
        dsm, dss = float(slide_deltas.mean()), float(slide_deltas.std())
    else:
        n_slides, dsm, dss = 0, float("nan"), float("nan")
        nz = d[d != 0]
        w_stat, w_pval = (wilcoxon(nz, alternative=alternative) if len(nz) >= 10
                          else (float("nan"), float("nan")))
        boot = np.array([d[rng.integers(0, n, size=n)].mean() for _ in range(n_bootstrap)])
    alpha = 1.0 - ci
    return {"wilcoxon_stat": float(w_stat), "wilcoxon_pvalue": float(w_pval),
            "ci_low": float(np.percentile(boot, 100 * alpha / 2)),
            "ci_high": float(np.percentile(boot, 100 * (1 - alpha / 2))),
            "n": n, "n_slides": n_slides, "delta_slide_mean": dsm, "delta_slide_std": dss}


def _apply_multiple_comparisons_correction(summary):
    locs = []
    for d in [summary.get("overall", {})] + list(summary["per_class"].values()) + list(summary["per_class_outcome"].values()):
        for k in ("deletion_wilcoxon_pvalue", "insertion_wilcoxon_pvalue"):
            if k in d:
                locs.append((d, k))
    raw = np.array([d[k] for d, k in locs], dtype=np.float64)
    M = len(raw)
    bonf = np.minimum(1.0, raw * M)
    for j, (d, k) in enumerate(locs):
        d[k.replace("_pvalue", "_pvalue_bonferroni")] = float(bonf[j])
    summary["n_hypothesis_tests"] = M


def compute_faithfulness_summary(fr, class_names):
    audc_gc, auic_gc, audc_rnd, auic_rnd = fr["audc_gradcam"], fr["auic_gradcam"], fr["audc_random"], fr["auic_random"]
    y_true, y_pred, sg_all = fr["true_labels"], fr["predicted_classes"], fr["slide_groups"]
    correct = y_true == y_pred
    delta_del, delta_ins = audc_rnd - audc_gc, auic_gc - auic_rnd

    def _stats(mask, seed_offset=0):
        if mask.sum() == 0:
            return {}
        sg = sg_all[mask]
        base = {"audc_gradcam_mean": float(audc_gc[mask].mean()), "auic_gradcam_mean": float(auic_gc[mask].mean()),
                "audc_random_mean": float(audc_rnd[mask].mean()), "auic_random_mean": float(auic_rnd[mask].mean()),
                "delta_deletion_mean": float(delta_del[mask].mean()), "delta_insertion_mean": float(delta_ins[mask].mean()),
                "n_samples": int(mask.sum()), "n_slides": int(len(np.unique(sg)))}
        for proto, a, b, off in (("deletion", audc_rnd, audc_gc, 0), ("insertion", auic_gc, auic_rnd, 1)):
            inf = _inferential_stats(a[mask], b[mask], "greater", rng_seed=seed_offset + off, slide_groups=sg)
            base[f"{proto}_wilcoxon_stat"] = inf["wilcoxon_stat"]
            base[f"{proto}_wilcoxon_pvalue"] = inf["wilcoxon_pvalue"]
            base[f"{proto}_ci95_low"], base[f"{proto}_ci95_high"] = inf["ci_low"], inf["ci_high"]
            base[f"delta_{proto}_slide_mean"] = inf["delta_slide_mean"]
        return base

    summary = {"overall": _stats(np.ones(len(audc_gc), bool), 0), "per_class": {}, "per_class_outcome": {}}
    for ci, cn in enumerate(class_names):
        s = _stats(y_true == ci, 100 * (ci + 1))
        if s:
            summary["per_class"][cn] = s
    for ci, cn in enumerate(class_names):
        for oi, (lab, om) in enumerate((("correct", correct), ("incorrect", ~correct))):
            s = _stats((y_true == ci) & om, 1000 * (ci + 1) + 10 * oi)
            if s:
                summary["per_class_outcome"][f"{cn}__{lab}"] = {"class": cn, "outcome": lab, **s}
    _apply_multiple_comparisons_correction(summary)
    return summary


def summary_table(summary) -> pd.DataFrame:
    rows = [{"group": "overall", **summary["overall"]}]
    rows += [{"group": f"class={k}", **v} for k, v in summary["per_class"].items()]
    rows += [{"group": k, **{kk: vv for kk, vv in v.items() if kk not in ("class", "outcome")}}
             for k, v in summary["per_class_outcome"].items()]
    return pd.DataFrame(rows)


def class_means(fr, key, cls):
    m = (fr["true_labels"] == cls) & (fr["true_labels"] == fr["predicted_classes"])
    return float(np.asarray(fr[key])[m].mean()) if m.any() else float("nan")


