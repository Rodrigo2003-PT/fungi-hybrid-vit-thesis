class NPYPatchDataset(torch.utils.data.Dataset):
    """Held-out images in dataset order; evaluation transform of training."""

    def __init__(self, preprocessed_dir: str, indices: List[int], mean, std, class_to_idx: Dict[str, int]):
        samples = []
        for cname in sorted(os.listdir(preprocessed_dir)):
            cdir = os.path.join(preprocessed_dir, cname)
            if not os.path.isdir(cdir) or cname not in class_to_idx:
                continue
            for fn in sorted(os.listdir(cdir)):
                if fn.endswith(".npy"):
                    samples.append((os.path.join(cdir, fn), class_to_idx[cname]))
        self.subset = [samples[i] for i in indices]
        self.paths = [p for p, _ in self.subset]
        self.labels = np.array([l for _, l in self.subset], dtype=np.int64)
        self.mean = np.asarray(mean, dtype=np.float32)
        self.std = np.asarray(std, dtype=np.float32)

    def __len__(self) -> int:
        return len(self.subset)

    def _load(self, i: int) -> np.ndarray:
        arr = np.load(self.paths[i])
        if arr.ndim == 2:
            arr = arr[np.newaxis]
        elif arr.ndim == 3:
            arr = arr.transpose(2, 0, 1)
        else:
            raise RuntimeError(f"Unexpected shape {arr.shape} for {self.paths[i]}")
        arr = arr.astype(np.float32)
        if arr.min() < -0.01 or arr.max() > 1.01:
            arr = np.clip(arr, 0.0, 1.0)
        return arr

    def __getitem__(self, i: int):
        t = torch.from_numpy(self._load(i))
        t = (t - torch.as_tensor(self.mean[:, None, None])) / (torch.as_tensor(self.std[:, None, None]) + 1e-8)
        return t, int(self.labels[i])

    def raw_image(self, i: int) -> np.ndarray:
        return self._load(i)[0]


